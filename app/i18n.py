    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    table = TRANSLATIONS[lang]
    default_table = TRANSLATIONS[DEFAULT_LANG]

    def t(key):
        return table.get(key, default_table.get(key, key))

    return t
